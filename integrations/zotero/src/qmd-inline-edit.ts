export type QmdEditableBlockKind =
  | "heading"
  | "paragraph"
  | "list-item"
  | "blockquote"
  | "inline-math"
  | "display-math"
  | "theorem-block"
  | "rich-block";

/**
 * One plain-text region that can be mapped losslessly between QMD and HTML.
 *
 * `source`, `start`, and `end` stay in privileged plugin code. The content
 * frame receives only `id`, `kind`, and rendered `text`, so an untrusted Draft
 * page cannot choose a filesystem range to overwrite.
 */
export interface QmdEditableBlock {
  id: string;
  kind: QmdEditableBlockKind;
  text: string;
  source: string;
  start: number;
  end: number;
  /** HTML id generated by Quarto for a thm/lem/def fenced div. */
  domId?: string;
  /** Rendered HTML block kind and source-order index for complex Markdown. */
  domKind?: "heading" | "paragraph" | "list-item" | "blockquote";
  ordinal?: number;
}

